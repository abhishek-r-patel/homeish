export type AnalyticsMetricKey = (typeof ANALYTICS_METRICS)[number]['key'];

export const ANALYTICS_METRIC_KEYS: readonly AnalyticsMetricKey[] =
  ANALYTICS_METRICS.map((metric) => metric.key);

const METRICS_BY_KEY = new Map<string, AnalyticsMetricDefinition>(
  ANALYTICS_METRICS.map((metric) => [metric.key, metric]),
);

export function getAnalyticsMetric(
  key: string,
): AnalyticsMetricDefinition | undefined {
  return METRICS_BY_KEY.get(key);
}
